#!/usr/bin/env python3
"""Single source for the color schemes. Writes src/brand.ts and the theme CSS block in src/styles.css.
Static pages (study guide, homework) import theme_css() / brands_json() from here via build_unit2_study.py.
Palettes are inspired by seasonal color-analysis boards; swatch colors for Dark Spring and Light Autumn were
sampled from the reference images, the others were matched by eye."""
import json, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
# id, label, dark(bg, panel, panel2, line, accent), light(bg, panel, panel2, line, accent, accent-fg)
THEMES = [
 ("classic",      "Classic",      ("#14111f", "#1e1a2e", "#2a2540", "#40395a", "#fceeaa"), ("#f8f5dc", "#fffef6", "#efe9c4", "#ddd6a8", "#2c2358", "#f6f1b5")),
 ("dark-winter",  "Dark Winter",  ("#0f0f24", "#191937", "#252556", "#3a3a78", "#a9a4f0"), ("#eeeffa", "#ffffff", "#dcdef4", "#c5c8e8", "#2f3190", "#e8e9ff")),
 ("light-summer", "Light Summer", ("#111823", "#1a2433", "#263449", "#3a4c66", "#c6f6ea"), ("#eaf8f4", "#ffffff", "#d4efe8", "#bfe3da", "#20606a", "#e0fbf5")),
 ("dark-summer",  "Dark Summer",  ("#171018", "#231a26", "#33263a", "#4d3a56", "#f0b4c8"), ("#fbeef2", "#ffffff", "#f4dbe3", "#e8c8d2", "#8a3a58", "#ffe6ee")),
 ("light-spring", "Light Spring", ("#12170f", "#1b2317", "#27321f", "#3d4d2e", "#d6ef8c"), ("#f4f9e0", "#fffff4", "#e6f0c0", "#d4e3a4", "#4b6a10", "#f0fbcf")),
 ("dark-spring",  "Dark Spring",  ("#1a130e", "#261b14", "#37271b", "#54402e", "#e3a574"), ("#fbf0e6", "#fffaf5", "#f1dcc8", "#e6cdb4", "#8a4018", "#ffe8d6")),
 ("light-autumn", "Light Autumn", ("#170d21", "#231433", "#321d49", "#4d3068", "#e6c072"), ("#f6eefa", "#ffffff", "#e8d9f1", "#d8c4e6", "#560e28", "#ffe9c4")),
]
DEFAULT = "classic"
def theme_css():
    """For pages with light + dark modes."""
    out = []
    for id_, _, (bg, pn, p2, ln, ac), (lbg, lpn, lp2, lln, lac, lfg) in THEMES:
        sel = f'[data-brand="{id_}"]'
        dark = f"--bg:{bg};--panel:{pn};--panel2:{p2};--line:{ln};--accent:{ac};--accent-fg:#1a1626;--focus:{ac}"
        light = f"--bg:{lbg};--panel:{lpn};--panel2:{lp2};--line:{lln};--accent:{lac};--accent-fg:{lfg};--focus:{lac};color-scheme:light"
        out += [f":root{sel}{{{dark}}}", f':root[data-theme="dark"]{sel}{{{dark}}}',
                f'@media (prefers-color-scheme:light){{:root:not([data-theme="dark"]){sel}{{{light}}}}}', f':root[data-theme="light"]{sel}{{{light}}}']
    return "\n".join(out)
def app_css():
    """The MathFacts app is dark only."""
    return "\n".join(f':root[data-brand="{t[0]}"] {{ --bg: {t[2][0]}; --panel: {t[2][1]}; --panel2: {t[2][2]}; --amber: {t[2][4]}; --amber-dim: {t[2][4]}99; }}' for t in THEMES)
SWATCH_CSS = """.swatches{display:flex;gap:12px;flex-wrap:wrap;justify-content:center}
.sw{display:flex;flex-direction:column;align-items:center;gap:6px;background:none;border:0;color:var(--muted);font-size:14px;min-width:78px;padding:4px;cursor:pointer;font-family:inherit}
.sw i{width:64px;height:44px;border-radius:12px;border:3px solid transparent;box-shadow:0 0 0 2px var(--line, #3a3354)}
.sw[aria-pressed=true] i{border-color:var(--bg);box-shadow:0 0 0 3px var(--text, var(--fg))}
.sw[aria-pressed=true]{color:var(--text, var(--fg))}"""
def brands_json():
    return json.dumps([dict(id=t[0], label=t[1], bg=t[2][0], accent=t[2][4]) for t in THEMES])
def write_ts():
    items = ",\n".join(f"  {{ id: '{t[0]}', label: '{t[1]}', bg: '{t[2][0]}', accent: '{t[2][4]}' }}" for t in THEMES)
    (ROOT / "src" / "brand.ts").write_text(f"""// GENERATED by tools/brand_themes.py. Do not edit by hand.
export const BRANDS = [
{items},
] as const;
export type BrandId = (typeof BRANDS)[number]['id'];
const KEY = 'mathseye.brand';
export function getBrand(): BrandId {{
  try {{ const v = localStorage.getItem(KEY); if (v && BRANDS.some((b) => b.id === v)) return v as BrandId; }} catch {{ /* private mode */ }}
  return '{DEFAULT}';
}}
export function applyBrand(id: BrandId = getBrand()) {{
  document.documentElement.dataset.brand = id;
  const bg = BRANDS.find((b) => b.id === id)?.bg;
  const meta = document.querySelector('meta[name="theme-color"]');
  if (bg && meta) meta.setAttribute('content', bg);
}}
export function setBrand(id: BrandId) {{ try {{ localStorage.setItem(KEY, id); }} catch {{ /* ignore */ }} applyBrand(id); }}
""")
    css = ROOT / "src" / "styles.css"; s = css.read_text(); a, b = "/* BRAND-THEMES START */", "/* BRAND-THEMES END */"
    block = f"{a}\n{app_css()}\n{SWATCH_CSS}\n{b}"
    s = (s[:s.index(a)] + block + s[s.index(b) + len(b):]) if a in s else s + "\n" + block + "\n"
    css.write_text(s)
if __name__ == "__main__": write_ts(); print("themes:", [t[0] for t in THEMES])
