#!/usr/bin/env python3
"""Guards for the color schemes (run after any edit to tools/brand_themes.py):
  1. WCAG contrast for every scheme in dark and light mode (text >= 7:1; other text and accent >= 4.5:1)
  2. src/brand.ts and the theme block in src/styles.css match what brand_themes.py would generate
  3. docs/COLOR-SCHEMES.md matches too
  python3 tools/check_themes.py          check only (exit 1 on any problem)
  python3 tools/check_themes.py --write  regenerate docs/COLOR-SCHEMES.md first"""
import pathlib, re, sys
sys.path.insert(0, str(pathlib.Path(__file__).parent))
import brand_themes as B
ROOT = B.ROOT
TEXT_DARK, MUTED_DARK, FG_ON_ACCENT_DARK = "#f1ecd8", "#b4aac4", "#1a1626"
TEXT_LIGHT, MUTED_LIGHT = "#1b1730", "#5b5570"
def lum(h):
    h = h.lstrip("#"); c = [int(h[i:i+2], 16) / 255 for i in (0, 2, 4)]
    c = [x / 12.92 if x <= 0.03928 else ((x + 0.055) / 1.055) ** 2.4 for x in c]; return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]
def ratio(a, b):
    la, lb = sorted((lum(a), lum(b)), reverse=True); return (la + 0.05) / (lb + 0.05)
def pairs(t):
    _, _, (bg, pn, p2, ln, ac), (lbg, lpn, lp2, lln, lac, lfg) = t
    return [("dark", "text on background", TEXT_DARK, bg, 7), ("dark", "text on panel", TEXT_DARK, pn, 7), ("dark", "text on panel 2", TEXT_DARK, p2, 7),
            ("dark", "muted text on panel", MUTED_DARK, pn, 4.5), ("dark", "muted text on background", MUTED_DARK, bg, 4.5),
            ("dark", "accent on background", ac, bg, 4.5), ("dark", "accent on panel", ac, pn, 4.5), ("dark", "button text on accent", FG_ON_ACCENT_DARK, ac, 4.5),
            ("light", "text on background", TEXT_LIGHT, lbg, 7), ("light", "text on panel", TEXT_LIGHT, lpn, 7), ("light", "text on panel 2", TEXT_LIGHT, lp2, 7),
            ("light", "muted text on panel", MUTED_LIGHT, lpn, 4.5), ("light", "muted text on background", MUTED_LIGHT, lbg, 4.5),
            ("light", "accent on background", lac, lbg, 4.5), ("light", "accent on panel", lac, lpn, 4.5), ("light", "button text on accent", lfg, lac, 4.5)]
def table_rows():
    return [(t[0], pairs(t)) for t in B.THEMES]
def doc():
    L = ["# Color schemes", "", "GENERATED by `tools/check_themes.py --write` from `tools/brand_themes.py`. Do not edit this file by hand; edit the table in `brand_themes.py`.", "",
         "Seven schemes. The student picks one on the home screen; the choice is saved on the device and shared by the app, study guide, and homework page.", "",
         "## How to tune a color", "1. Edit the row in `THEMES` in `tools/brand_themes.py` (hex values only).",
         "2. Run `python3 tools/brand_themes.py && python3 tools/build_unit2_study.py <scratch-dir>` to regenerate the app CSS, `src/brand.ts`, and the static pages.",
         "3. Run `python3 tools/check_themes.py --write`. It fails if any pair drops below the contrast limit or if generated files are out of date.",
         "4. Look at it on the iPad in dark and light mode.", "",
         "## Where the colors came from",
         "Palettes are inspired by six seasonal color-analysis boards the owner shared, plus a Classic scheme that keeps the original ink-and-butter brand.",
         "- **Sampled exactly from the image:** Dark Spring and Light Autumn swatches.", "- **Matched by eye** (image not on disk): Dark Winter, Light Summer, Dark Summer, Light Spring.",
         "- **Classic:** ink navy `#14111f` and butter yellow `#fceeaa` (the yellow chip hex the owner gave).",
         "- Scheme names are palette names. No scheme is tied to a person.", "",
         "## Shared text colors (all schemes)", f"- Dark mode: text `{TEXT_DARK}`, muted `{MUTED_DARK}`, text on accent `{FG_ON_ACCENT_DARK}`", f"- Light mode: text `{TEXT_LIGHT}`, muted `{MUTED_LIGHT}`", "",
         "## Schemes", ""]
    for t, rows in table_rows():
        id_, label, d, l = next(x for x in B.THEMES if x[0] == t)[0], next(x for x in B.THEMES if x[0] == t)[1], next(x for x in B.THEMES if x[0] == t)[2], next(x for x in B.THEMES if x[0] == t)[3]
        L += [f"### {label} (`{id_}`)", "", "| Mode | Background | Panel | Panel 2 | Line | Accent | Text on accent |", "| --- | --- | --- | --- | --- | --- | --- |",
              f"| Dark | `{d[0]}` | `{d[1]}` | `{d[2]}` | `{d[3]}` | `{d[4]}` | `{FG_ON_ACCENT_DARK}` |", f"| Light | `{l[0]}` | `{l[1]}` | `{l[2]}` | `{l[3]}` | `{l[4]}` | `{l[5]}` |", "",
              "| Mode | Pair | Contrast | Needs | Result |", "| --- | --- | --- | --- | --- |"]
        for mode, name, fg, bg, need in rows:
            r = ratio(fg, bg); L.append(f"| {mode} | {name} | {r:.1f}:1 | {need}:1 | {'pass' if r >= need else '**FAIL**'} |")
        L.append("")
    return "\n".join(L) + "\n"
def main():
    write = "--write" in sys.argv; errs = []
    for t, rows in table_rows():
        for mode, name, fg, bg, need in rows:
            if ratio(fg, bg) < need: errs.append(f"contrast {t} {mode} {name}: {ratio(fg, bg):.2f} < {need}")
    ts, css = ROOT / "src/brand.ts", ROOT / "src/styles.css"; before = (ts.read_text(), css.read_text())
    B.write_ts(); after = (ts.read_text(), css.read_text())
    if before != after and not write: errs.append("src/brand.ts or styles.css were out of date (regenerated now; commit them)")
    d = ROOT / "docs/COLOR-SCHEMES.md"
    if write: d.write_text(doc())
    elif not d.exists() or d.read_text() != doc(): errs.append("docs/COLOR-SCHEMES.md is out of date (run with --write)")
    for e in errs: print("ERROR", e)
    print(f"{len(B.THEMES)} schemes, {sum(len(r) for _, r in table_rows())} contrast pairs checked, {len(errs)} problem(s)")
    sys.exit(1 if errs else 0)
main()
